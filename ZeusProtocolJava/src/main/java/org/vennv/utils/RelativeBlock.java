package org.vennv.utils;

public class RelativeBlock {
    public final int dx;
    public final int dy;
    public final int dz;
    public final String type;

    public RelativeBlock(int dx, int dy, int dz, String type) {
        this.dx = dx;
        this.dy = dy;
        this.dz = dz;
        this.type = type;
    }
}
